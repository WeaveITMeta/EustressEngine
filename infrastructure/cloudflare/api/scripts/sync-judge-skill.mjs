// Copies the listing judge's rules into the creator-facing eustress-judge skill, so the skill cannot drift from the judge
// silently. The skill's hand-written parts (SKILL.md, scripts/verdict.mjs) live in .agents/skills/eustress-judge; this script
// writes two generated references beside them and mirrors the whole skill into the other agent folders:
//   references/code.md        the Guardian Code exactly as the judge receives it (docs/architecture/AI_GUARDIAN_POLICY_v1.0.md)
//   references/findings.json  the author copy Studio shows (title, why, what to change) and the deterministic lists
//                             (statement categories, fiction tags) from src/moderation.mjs
// `--check` exits 1 when any copy has drifted; tests/judge_skill_sync.test.mjs runs the same comparison.
// Run `npm run sync-judge-skill` after changing the Code, AUTHOR_COPY or the statement or fiction rules.
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, join, relative } from 'node:path';
import {
  AUTHOR_COPY, POLICY_VERSION, REVIEW_SCHEMA, STATEMENT_CATEGORIES, FICTION_TAG, FICTION_GENRE_TAGS, CODE_TESTS,
  GROUP_A, GROUP_B, RATINGS, CONTENT_DESCRIPTORS,
} from '../src/moderation.mjs';
import { JUDGE_TAGS_MAX } from '../src/tags.mjs';

const here = dirname(fileURLToPath(import.meta.url));
export const REPO = resolve(here, '..', '..', '..', '..');
export const CODE_SOURCE = resolve(REPO, 'docs', 'architecture', 'AI_GUARDIAN_POLICY_v1.0.md');
/// The skill's home: SKILL.md and scripts/ are edited here, by hand.
export const CANONICAL = resolve(REPO, '.agents', 'skills', 'eustress-judge');
/// Copies kept identical to the canonical folder. A mirror whose parent folder is absent (`.claude/` is not in git) is skipped.
export const MIRRORS = [resolve(REPO, '.windsurf', 'skills', 'eustress-judge'), resolve(REPO, '.claude', 'skills', 'eustress-judge')];

const lf = s => s.replace(/\r\n/g, '\n');

/// The generated files, by path relative to the skill folder.
export function generated() {
  const code = lf(readFileSync(CODE_SOURCE, 'utf8'));
  const codeSha = 'sha256:' + createHash('sha256').update(code, 'utf8').digest('hex');
  const header = '<!-- GENERATED by infrastructure/cloudflare/api/scripts/sync-judge-skill.mjs from docs/architecture/AI_GUARDIAN_POLICY_v1.0.md.\n'
    + '     Do not edit here: edit the Code and run `npm run sync-judge-skill` in infrastructure/cloudflare/api. -->\n\n';
  const findings = {
    _generated: 'by infrastructure/cloudflare/api/scripts/sync-judge-skill.mjs from src/moderation.mjs and src/tags.mjs; do not edit',
    policy_version: POLICY_VERSION,
    review_schema: REVIEW_SCHEMA,
    code_sha256: codeSha,
    tests: Object.fromEntries(CODE_TESTS.map((k, i) => [k, `T${i + 1}`])),
    statement: {
      labels: ['Category', 'Objective', 'Lesson', 'Real-world link'],
      categories: STATEMENT_CATEGORIES,
      value_max_chars: 300,
      rule: 'A label starts its line, any case, then a colon. The first line with a label counts. Present only when all four lines have text after the label and the Category is one of the list (a trailing period is ignored).',
    },
    fiction: { tag: FICTION_TAG, genre_tags: FICTION_GENRE_TAGS, genre_suffixes: ['-fiction', '-fi'] },
    tags: { max_author_tags: 8, max_review_tags: JUDGE_TAGS_MAX, shape: '^[a-z0-9]+(?:-[a-z0-9]+)*$' },
    articles: { group_a: GROUP_A, group_b: GROUP_B },
    ratings: RATINGS,
    descriptors: CONTENT_DESCRIPTORS,
    author_copy: Object.fromEntries(Object.entries(AUTHOR_COPY).filter(([k]) => k !== 'requested_change')),
  };
  return {
    'references/code.md': header + code,
    'references/findings.json': JSON.stringify(findings, null, 2) + '\n',
  };
}

function walk(dir, base = dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, base, out);
    else out.push(relative(base, p).replace(/\\/g, '/'));
  }
  return out;
}

/// Every file each skill folder should hold, as [absolute path, expected text].
export function expectedFiles() {
  if (!existsSync(join(CANONICAL, 'SKILL.md'))) throw new Error(`${CANONICAL}/SKILL.md is missing`);
  const gen = generated();
  const files = new Map();
  for (const rel of walk(CANONICAL)) if (!(rel in gen)) files.set(rel, lf(readFileSync(join(CANONICAL, rel), 'utf8')));
  for (const [rel, text] of Object.entries(gen)) files.set(rel, text);
  const out = [];
  for (const root of [CANONICAL, ...MIRRORS.filter(m => existsSync(dirname(m)))]) {
    for (const [rel, text] of files) out.push([join(root, rel), text]);
  }
  return out;
}

/// The files whose content differs from what they should be (CRLF and LF compare equal: a Windows checkout may write either).
export function drift() {
  return expectedFiles().filter(([path, text]) => !existsSync(path) || lf(readFileSync(path, 'utf8')) !== text).map(([path]) => path);
}

const invokedDirectly = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  if (process.argv.includes('--check')) {
    // A deploy export (git archive of the API and docs) does not carry .agents/; there is nothing to compare.
    if (!existsSync(CANONICAL)) { console.log(`eustress-judge skill not in this checkout (${CANONICAL}); check skipped`); process.exit(0); }
    const stale = drift();
    if (stale.length) { console.error(`eustress-judge skill is out of date; run npm run sync-judge-skill:\n  ${stale.join('\n  ')}`); process.exit(1); }
    console.log('eustress-judge skill in sync');
  } else {
    for (const [path, text] of expectedFiles()) {
      mkdirSync(dirname(path), { recursive: true });
      if (!existsSync(path) || lf(readFileSync(path, 'utf8')) !== text) { writeFileSync(path, text); console.log(`wrote ${relative(REPO, path)}`); }
    }
  }
}
