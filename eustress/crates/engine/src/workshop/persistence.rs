//! # Workshop Conversation Persistence
//!
//! Stores ideation session history in a Windsurf-compatible format:
//! ~/.eustress_engine/workshop/history/{session_id}/entries.json
//!
//! ## Table of Contents
//!
//! 1. SessionEntry — individual message/event record
//! 2. SessionManifest — session-level metadata (version, resource, entries list)
//! 3. save_session / load_session — read/write session files
//! 4. list_sessions — enumerate past sessions for history browsing
//!
//! ## Format
//!
//! Modeled after Windsurf's History format:
//! ```json
//! {
//!     "version": 1,
//!     "resource": "workshop://ideation/{session_id}",
//!     "product_name": "V-Cell 4680",
//!     "entries": [
//!         {
//!             "id": "msg_001",
//!             "source": "user",
//!             "content": "Solid-state sodium-sulfur battery...",
//!             "timestamp": 1710000000000
//!         }
//!     ]
//! }
//! ```
//!
//! Cross-OS: uses dirs::home_dir() for ~/.eustress_engine/ on all platforms.

use serde::{Deserialize, Serialize};
use std::path::PathBuf;
use bevy::log::{debug, info, warn};

use super::{ChatMessage, IdeationPipeline};

// ============================================================================
// 1. SessionEntry — individual message record
// ============================================================================

/// A single entry in the session history file
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SessionEntry {
    /// Entry identifier (message ID as string)
    pub id: String,
    /// Source role: "user", "system", "mcp", "artifact", "error"
    pub source: String,
    /// Message content
    pub content: String,
    /// Unix timestamp in milliseconds
    pub timestamp: u64,
    /// Optional MCP endpoint (for MCP command entries)
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub mcp_endpoint: Option<String>,
    /// Optional MCP status
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub mcp_status: Option<String>,
    /// Optional artifact path
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub artifact_path: Option<String>,
    /// Optional artifact type
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub artifact_type: Option<String>,
    /// Cost of this entry's API call in USD
    #[serde(default)]
    pub cost: f64,
}

// ============================================================================
// 2. SessionManifest — session-level metadata
// ============================================================================

/// Top-level session file matching Windsurf History format
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SessionManifest {
    /// Schema version (always 1 for now)
    pub version: u32,
    /// Resource URI: workshop://ideation/{session_id}
    pub resource: String,
    /// Product name (if known)
    #[serde(default)]
    pub product_name: String,
    /// Pipeline state when saved
    #[serde(default)]
    pub pipeline_state: String,
    /// Total BYOK API cost for this session
    #[serde(default)]
    pub total_cost: f64,
    /// Short human-readable label for the session, shown in the
    /// Workshop tab strip and session history list. Generated by a
    /// Claude Haiku call from the first user message — absent until
    /// that async call completes. Callers fall back to a truncated
    /// first-message preview when `None`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub title: Option<String>,
    /// All conversation entries
    pub entries: Vec<SessionEntry>,
}

// ============================================================================
// 3. Path helpers
// ============================================================================

/// Get the workshop history root directory within the current Space.
/// {SpaceRoot}/SoulService/Workshop/
pub fn history_root_for_space(space_root: Option<&std::path::Path>) -> PathBuf {
    space_root
        .map(|root| root.join("SoulService").join("Workshop"))
        .expect("Workshop requires an active Space. No SpaceRoot available.")
}

/// Get the session directory for a specific session ID
pub fn session_dir_in_space(space_root: Option<&std::path::Path>, session_id: &str) -> PathBuf {
    history_root_for_space(space_root).join(session_id)
}

/// Get the entries.json path for a specific session ID
pub fn session_entries_path_in_space(space_root: Option<&std::path::Path>, session_id: &str) -> PathBuf {
    session_dir_in_space(space_root, session_id).join("entries.json")
}

/// Get the _instance.toml path for a conversation (makes it an Explorer entity)
pub fn session_instance_path(space_root: Option<&std::path::Path>, session_id: &str) -> PathBuf {
    session_dir_in_space(space_root, session_id).join("_instance.toml")
}

// ============================================================================
// 4. Save / Load
// ============================================================================

/// Convert a ChatMessage to a SessionEntry
fn message_to_entry(msg: &ChatMessage) -> SessionEntry {
    // Parse ISO 8601 timestamp to millis, fallback to 0
    let timestamp = chrono::DateTime::parse_from_rfc3339(&msg.timestamp)
        .map(|dt| dt.timestamp_millis() as u64)
        .unwrap_or(0);
    
    SessionEntry {
        id: format!("msg_{:04}", msg.id),
        source: msg.role.to_slint_string().to_string(),
        content: msg.content.clone(),
        timestamp,
        mcp_endpoint: msg.mcp_endpoint.clone(),
        mcp_status: msg.mcp_status.as_ref().map(|s| s.to_slint_string().to_string()),
        artifact_path: msg.artifact_path.as_ref().map(|p| p.display().to_string()),
        artifact_type: msg.artifact_type.as_ref().map(|t| t.to_slint_string().to_string()),
        cost: msg.estimated_cost,
    }
}

/// Save the current ideation session to the Space's SoulService/Workshop/ directory.
/// Creates an _instance.toml so the file loader picks it up as a WorkshopConversation entity.
pub fn save_session_to_space(pipeline: &IdeationPipeline, space_root: Option<&std::path::Path>) -> Result<(), String> {
    let entries_path = session_entries_path_in_space(space_root, &pipeline.session_id);

    // Ensure directory exists
    if let Some(parent) = entries_path.parent() {
        std::fs::create_dir_all(parent)
            .map_err(|e| format!("Failed to create session directory: {}", e))?;
    }

    // Preserve the title across saves. The Haiku title generator runs
    // out-of-band and writes back to `entries.json` asynchronously —
    // reading the existing manifest first (if any) avoids clobbering
    // a title that landed between saves.
    let existing_title = std::fs::read_to_string(&entries_path)
        .ok()
        .and_then(|s| serde_json::from_str::<SessionManifest>(&s).ok())
        .and_then(|m| m.title);

    let manifest = SessionManifest {
        version: 1,
        resource: format!("workshop://ideation/{}", pipeline.session_id),
        product_name: pipeline.product_name.clone(),
        pipeline_state: pipeline.state_string().to_string(),
        total_cost: pipeline.total_cost,
        title: existing_title,
        entries: pipeline.messages.iter().map(message_to_entry).collect(),
    };

    let json = serde_json::to_string_pretty(&manifest)
        .map_err(|e| format!("Failed to serialize session: {}", e))?;

    std::fs::write(&entries_path, json)
        .map_err(|e| format!("Failed to write {}: {}", entries_path.display(), e))?;

    // Write _instance.toml so Explorer shows this as a WorkshopConversation entity
    let instance_path = session_instance_path(space_root, &pipeline.session_id);
    if !instance_path.exists() {
        let display_name = if pipeline.product_name.is_empty() {
            format!("Session {}", pipeline.session_id.chars().take(8).collect::<String>())
        } else {
            pipeline.product_name.clone()
        };
        let now = chrono::Utc::now().to_rfc3339();
        let instance_toml = format!(
            "[metadata]\nclass_name = \"WorkshopConversation\"\narchivable = true\nname = \"{}\"\ncreated = \"{}\"\nlast_modified = \"{}\"\n\n[properties]\nsession_id = \"{}\"\nproduct_name = \"{}\"\nmessage_count = {}\ntotal_cost = {:.4}\n",
            display_name, now, now,
            pipeline.session_id, pipeline.product_name,
            pipeline.messages.len(), pipeline.total_cost,
        );
        std::fs::write(&instance_path, instance_toml)
            .map_err(|e| format!("Failed to write instance TOML: {}", e))?;
    }

    info!("Workshop: Saved session {} ({} entries) to {:?}",
          pipeline.session_id, manifest.entries.len(), entries_path);

    Ok(())
}


/// Load a session from the Space's SoulService/Workshop/ directory
pub fn load_session_from_space(space_root: Option<&std::path::Path>, session_id: &str) -> Result<SessionManifest, String> {
    let path = session_entries_path_in_space(space_root, session_id);

    let json = std::fs::read_to_string(&path)
        .map_err(|e| format!("Failed to read {}: {}", path.display(), e))?;

    let manifest: SessionManifest = serde_json::from_str(&json)
        .map_err(|e| format!("Failed to parse {}: {}", path.display(), e))?;

    // debug!, not info! — this is called for every session on every
    // scan (twice per second via `sync_workshop_sessions_to_slint` and
    // `generate_workshop_titles`), so an info-level log here floods the
    // console with 4×N lines/sec. User-initiated loads (slint_ui.rs)
    // can log at a higher level from the call site if needed.
    debug!("Workshop: Loaded session {} ({} entries)", session_id, manifest.entries.len());
    Ok(manifest)
}


/// A message cut for a list row: trimmed, and at most `max` CHARACTERS, with an
/// ellipsis when it was cut. The cut is on a character boundary. It used to slice
/// the byte string at 40 and 80, which panics whenever a multi-byte character
/// (an accented letter, CJK, an emoji) straddles that byte, so listing past
/// conversations took the engine down; counting bytes also shortened non-Latin
/// text to a third of what was meant.
fn preview(text: &str, max: usize) -> String {
    let trimmed = text.trim();
    match trimmed.char_indices().nth(max) {
        Some((cut, _)) => format!("{}…", &trimmed[..cut]),
        None => trimmed.to_string(),
    }
}

#[cfg(test)]
mod preview_tests {
    use super::preview;

    #[test]
    fn thirty_nine_letters_then_an_accented_one_does_not_panic() {
        // The reported case: a character that straddles byte 40.
        let text = format!("{}\u{e9}", "a".repeat(39));
        assert_eq!(preview(&text, 40), text, "40 characters fit whole");
        assert_eq!(preview(&format!("{text}z"), 40), format!("{text}\u{2026}"), "41 characters are cut");
    }

    #[test]
    fn emoji_and_cjk_are_cut_between_characters() {
        let emoji = format!("{}{}", "a".repeat(38), "\u{1F642}".repeat(3));
        assert_eq!(preview(&emoji, 40), format!("{}{}\u{2026}", "a".repeat(38), "\u{1F642}".repeat(2)));
        // Thirty CJK characters are 90 bytes but only 30 characters: not cut at all.
        let cjk = "\u{4e2d}".repeat(30);
        assert_eq!(preview(&cjk, 40), cjk);
        assert_eq!(preview(&"\u{4e2d}".repeat(100), 80).chars().count(), 81);
    }

    #[test]
    fn the_limit_counts_characters_exactly() {
        assert_eq!(preview(&"b".repeat(40), 40), "b".repeat(40));
        assert_eq!(preview(&"b".repeat(41), 40), format!("{}\u{2026}", "b".repeat(40)));
        assert_eq!(preview(&"b".repeat(80), 80), "b".repeat(80));
        assert_eq!(preview(&"b".repeat(81), 80).chars().count(), 81);
    }

    #[test]
    fn whitespace_is_trimmed_and_nothing_is_nothing() {
        assert_eq!(preview("   hello \n", 40), "hello");
        assert_eq!(preview("", 40), "");
        assert_eq!(preview(" \t\n ", 80), "");
    }

    #[test]
    fn no_position_of_a_multi_byte_character_can_panic() {
        // A two-byte, three-byte and four-byte character placed at every offset around
        // both cut points.
        for wide in ["\u{e9}", "\u{4e2d}", "\u{1F642}"] {
            for lead in 0..120 {
                let text = format!("{}{}{}", "a".repeat(lead), wide, "tail".repeat(40));
                for max in [40usize, 80] {
                    let shown = preview(&text, max);
                    assert!(shown.chars().count() <= max + 1, "{wide} at {lead}, max {max}");
                }
            }
        }
    }
}

/// List all past sessions from the Space's SoulService/Workshop/ directory (newest first)
pub fn list_sessions_in_space(space_root: Option<&std::path::Path>) -> Vec<SessionSummary> {
    let root = history_root_for_space(space_root);

    if !root.exists() {
        return Vec::new();
    }

    let mut sessions = Vec::new();

    if let Ok(entries) = std::fs::read_dir(&root) {
        for entry in entries.flatten() {
            let path = entry.path();
            if !path.is_dir() { continue; }

            let session_id = path.file_name()
                .and_then(|n| n.to_str())
                .unwrap_or("")
                .to_string();

            if session_id.is_empty() { continue; }

            // Try to read the manifest for metadata
            match load_session_from_space(space_root, &session_id) {
                Ok(manifest) => {
                    let last_timestamp = manifest.entries.last()
                        .map(|e| e.timestamp)
                        .unwrap_or(0);

                    // Title fallback: stored title → product_name →
                    // first-user-message preview → short session id.
                    // The tab strip shows this string, so we always
                    // return *something* rather than an empty string.
                    let title = manifest.title.clone()
                        .filter(|t| !t.trim().is_empty())
                        .or_else(|| {
                            if !manifest.product_name.is_empty() {
                                Some(manifest.product_name.clone())
                            } else {
                                None
                            }
                        })
                        .or_else(|| {
                            manifest.entries.iter()
                                .find(|e| e.source == "user")
                                .map(|e| preview(&e.content, 40))
                        })
                        .unwrap_or_else(|| {
                            // Last resort — short session id.
                            session_id.chars().take(8).collect::<String>()
                        });
                    let first_message = manifest.entries.iter()
                        .find(|e| e.source == "user")
                        .map(|e| preview(&e.content, 80))
                        .unwrap_or_default();

                    sessions.push(SessionSummary {
                        session_id,
                        title,
                        first_message,
                        product_name: manifest.product_name,
                        pipeline_state: manifest.pipeline_state,
                        total_cost: manifest.total_cost,
                        entry_count: manifest.entries.len(),
                        last_timestamp,
                    });
                }
                Err(e) => {
                    warn!("Workshop: Failed to read session {}: {}", session_id, e);
                }
            }
        }
    }

    sessions.sort_by(|a, b| b.last_timestamp.cmp(&a.last_timestamp));
    sessions
}

/// Write `title` into a session's manifest on disk. Called by the
/// Haiku title-generation system once the async API call returns.
/// Round-trips the rest of the manifest untouched so a concurrent
/// save doesn't lose data.
///
/// **Folder rename.** When the session's on-disk folder is still the
/// raw UUID (hash-named — the default for fresh sessions), this also
/// renames the folder to `{slug(title)}-{hash8}/` so Explorer + OS
/// file browsers show the human-readable title at a glance. The
/// short hash suffix keeps identically-titled sessions unique.
/// Returns the session's current folder name (which becomes the new
/// `session_id` if the rename succeeded, or the original id otherwise)
/// so the caller can update any live references.
///
/// If the folder is already slugified (user opened an older session
/// after this feature shipped), we leave it alone — idempotent.
pub fn update_session_title(
    space_root: Option<&std::path::Path>,
    session_id: &str,
    title: &str,
) -> Result<String, String> {
    let path = session_entries_path_in_space(space_root, session_id);
    let body = std::fs::read_to_string(&path)
        .map_err(|e| format!("read {}: {}", path.display(), e))?;
    let mut manifest: SessionManifest = serde_json::from_str(&body)
        .map_err(|e| format!("parse manifest: {}", e))?;
    manifest.title = Some(title.trim().to_string());
    let updated = serde_json::to_string_pretty(&manifest)
        .map_err(|e| format!("serialize manifest: {}", e))?;
    std::fs::write(&path, updated)
        .map_err(|e| format!("write {}: {}", path.display(), e))?;

    // Folder rename — only when the current folder name looks like a
    // raw UUID (32 hex-ish chars with dashes). Avoids clobbering a
    // custom folder name the user may have set manually.
    if !looks_like_uuid_folder(session_id) {
        return Ok(session_id.to_string());
    }

    let hash_suffix: String = session_id
        .chars()
        .filter(|c| c.is_ascii_alphanumeric())
        .take(8)
        .collect();
    let slug = slugify_title(title);
    if slug.is_empty() {
        return Ok(session_id.to_string());
    }
    let new_name = format!("{}-{}", slug, hash_suffix);
    if new_name == session_id {
        return Ok(session_id.to_string());
    }

    let old_dir = session_dir_in_space(space_root, session_id);
    let new_dir = session_dir_in_space(space_root, &new_name);
    if new_dir.exists() {
        // Collision with an existing slug+hash folder (very unlikely
        // but possible if two sessions share the first 8 hex chars
        // AND identical titles). Keep the UUID name so we don't
        // merge folders.
        return Ok(session_id.to_string());
    }
    match std::fs::rename(&old_dir, &new_dir) {
        Ok(_) => Ok(new_name),
        Err(_) => Ok(session_id.to_string()), // keep old id on failure
    }
}

/// True when a folder name looks like a raw UUID4 string
/// (`a3f24e8b-...`). Used to decide whether to rename on title
/// generation. We don't do a strict UUID-v4 parse because older
/// engines produced variant formats; length + hex/dash ratio is
/// sufficient in practice.
fn looks_like_uuid_folder(name: &str) -> bool {
    if name.len() < 32 || name.len() > 40 { return false; }
    name.chars().all(|c| c.is_ascii_hexdigit() || c == '-')
}

/// Lowercase, strip non-alphanumerics to hyphens, collapse runs,
/// trim, cap length. Matches what the file-system + Explorer
/// tolerate without surprises.
fn slugify_title(title: &str) -> String {
    let mut out = String::with_capacity(title.len());
    let mut prev_hyphen = true; // suppress leading hyphens
    for c in title.chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c.to_ascii_lowercase());
            prev_hyphen = false;
        } else if !prev_hyphen {
            out.push('-');
            prev_hyphen = true;
        }
    }
    while out.ends_with('-') { out.pop(); }
    if out.len() > 40 { out.truncate(40); }
    while out.ends_with('-') { out.pop(); }
    out
}

/// Summary of a past session for history browsing + tab strip.
///
/// `title` is the short label shown in the UI — generated by Claude
/// Haiku from the first user message when available, otherwise
/// synthesised from product_name / first-message preview / session id
/// so the field is always populated.
#[derive(Debug, Clone)]
pub struct SessionSummary {
    pub session_id: String,
    pub title: String,
    pub first_message: String,
    pub product_name: String,
    pub pipeline_state: String,
    pub total_cost: f64,
    pub entry_count: usize,
    pub last_timestamp: u64,
}
