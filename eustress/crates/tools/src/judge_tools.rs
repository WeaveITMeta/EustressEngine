// The Eustress listing review (the Guardian Code judge), built into the tool
// registry so an agent can check that a Space is listable from the start of the
// project, not after a real review turns it down. They are the tool face of the
// `eustress-judge` skill (.agents/skills/eustress-judge):
//
//   judge_guide          what the Code says, in plain words (offline)
