    #[test]
    fn publish_toml_is_parsed_with_escaped_line_ends_and_falls_back_to_the_space() {
        let base = std::env::temp_dir().join(format!("eustress_judge_tools_{}", std::process::id()));
        let universe = base.join("Universe");
        let space = universe.join("Spaces").join("S1");
        std::fs::create_dir_all(universe.join(".eustress")).unwrap();
        std::fs::create_dir_all(space.join(".eustress")).unwrap();
        // The description's line ends are written as escapes, exactly as Studio writes them.
        std::fs::write(
            universe.join(".eustress").join("publish.toml"),
            "[publish]\nstate = \"x\"\n\n[listing]\nname = \"Wind tunnel\"\ndescription = \"A twin.\\r\\nCategory: Digital twin\\r\\nObjective: o\\r\\nLesson: l\\r\\nReal-world link: r\"\ntags = [\"physics\", \"wind-tunnel\"]\n\n[visibility]\nis_public = false\n",
        )
        .unwrap();
        std::fs::write(space.join(".eustress").join("publish.toml"), "[listing]\nname = \"Space name\"\ndescription = \"Space description\"\n").unwrap();

        let ctx = ctx_in(&universe, &space);
        let l = resolve_listing(&json!({}), None, &ctx);
        assert_eq!(l.name, "Wind tunnel");
        assert!(l.description.contains('\r') && !l.description.contains("\\r"));
        assert_eq!(l.tags, vec!["physics", "wind-tunnel"]);
        assert!(!l.is_public);
        let f = findings().unwrap();
        let (found, st) = check_listing(&f, &l.name, &l.description, &l.tags);
        assert!(st.present(), "the statement must read through the escaped line ends: {st:?}");
        assert!(!found.iter().any(|v| v["code"] == "statement_missing"));

        // An argument wins over the file; the Space's file answers when the Universe has none.
        let l2 = resolve_listing(&json!({ "name": "Argument name" }), None, &ctx);
        assert_eq!(l2.name, "Argument name");
        assert!(l2.description.contains("Digital twin"));
        let bare_universe = base.join("Bare");
        std::fs::create_dir_all(&bare_universe).unwrap();
        let l3 = resolve_listing(&json!({}), None, &ctx_in(&bare_universe, &space));
        assert_eq!(l3.name, "Space name");

        // The tool itself, end to end and offline.
        let r = JudgeCheckListingTool.execute(json!({}), &ctx);
        assert!(r.success, "{}", r.content);
        assert!(r.content.contains("Guardian Code v"));
        assert!(r.content.contains("deterministic checks only"));
        let none = JudgeCheckListingTool.execute(json!({}), &ctx_in(&base.join("Nowhere"), &base.join("Nowhere")));
        assert!(!none.success);
        let _ = std::fs::remove_dir_all(&base);
    }

