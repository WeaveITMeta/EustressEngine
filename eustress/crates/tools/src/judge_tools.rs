fn normalized(text: &str) -> String {
    text.replace("\r\n", "\n").replace('\r', "\n")
}

fn findings() -> Result<Value, String> {
    serde_json::from_str(FINDINGS_JSON).map_err(|e| format!("the embedded findings.json does not parse: {e}"))
}

fn policy_version(f: &Value) -> String {
    f["policy_version"].as_str().unwrap_or("?").to_string()
}

/// Every block of `text` that starts at a line `start` accepts and runs to the
/// line before the next one `stop` accepts. Lines inside a code fence never
/// start or stop a block.
fn extract_blocks(text: &str, start: &dyn Fn(&str) -> bool, stop: &dyn Fn(&str) -> bool) -> Vec<String> {
    let mut blocks: Vec<String> = Vec::new();
    let mut current: Option<Vec<&str>> = None;
    let mut in_fence = false;
    let text = normalized(text);
    for line in text.split('\n') {
        let fence = line.trim_start().starts_with("```");
        if let Some(lines) = current.as_mut() {
            if !in_fence && !fence && stop(line) {
                blocks.push(lines.join("\n").trim_end().to_string());
                current = None;
            } else {
                lines.push(line);
            }
        }
        if current.is_none() && !in_fence && !fence && start(line) {
            current = Some(vec![line]);
        }
        if fence {
            in_fence = !in_fence;
        }
    }
    if let Some(lines) = current {
        blocks.push(lines.join("\n").trim_end().to_string());
    }
    blocks
}

/// One `## N.` section of the skill.
fn skill_section(prefix: &str) -> Option<String> {
    extract_blocks(SKILL_MD, &|l: &str| l.starts_with(prefix), &|l: &str| l.starts_with("## "))
        .into_iter()
        .next()
}

/// An article or test of the Code by its id ("B3", "T4"): its bold line and any
/// continuation, plus a sibling that shares the id ("T4 for Fiction").
fn code_article(id: &str) -> Vec<String> {
    let dot = format!("- **{id}.");
    let bold_dot = format!("**{id}.");
    let bold_sp = format!("**{id} ");
    extract_blocks(
        CODE_MD,
        &|l: &str| l.starts_with(&dot) || l.starts_with(&bold_dot) || l.starts_with(&bold_sp),
        &|l: &str| l.starts_with("- **") || l.starts_with("**") || l.starts_with('#'),
    )
}

/// A whole Part of the Code ("part ix"), its subsections included.
fn code_part(lower_name: &str) -> Vec<String> {
    let dot = format!("## {lower_name}.");
    let sp = format!("## {lower_name} ");
    extract_blocks(
        CODE_MD,
        &|l: &str| {
            let l = l.to_ascii_lowercase();
            l.starts_with(&dot) || l.starts_with(&sp)
        },
        &|l: &str| l.starts_with("## ") || l.starts_with("# "),
    )
}

fn is_article_id(s: &str) -> bool {
    let mut chars = s.chars();
    match chars.next() {
        Some(c) if matches!(c.to_ascii_uppercase(), 'A' | 'B' | 'T') => {}
        _ => return false,
    }
    let rest: &str = &s[1..];
    !rest.is_empty() && rest.chars().all(|c| c.is_ascii_digit())
}

fn statement_topic(f: &Value) -> String {
    let labels: Vec<String> = f["statement"]["labels"]
        .as_array()
        .map(|a| a.iter().filter_map(|v| v.as_str().map(String::from)).collect())
        .unwrap_or_default();
    let cats = string_list(&f["statement"]["categories"]);
    let mut out = String::new();
    out.push_str("The Qualification Statement (Code Part III): four labelled lines in the listing description, each on its own line. The review extracts them by machine, so the format is exact.\n\n");
    out.push_str("Category: <one of the list below>\nObjective: one sentence\nLesson: one sentence\nReal-world link: one sentence\n\n");
    out.push_str(&format!("Labels: {}.\n", labels.join(", ")));
    out.push_str(&format!("Category is exactly one of: {}.\n", cats.join(", ")));
    if let Some(rule) = f["statement"]["rule"].as_str() {
        out.push_str(&format!("Rule: {rule}\n"));
    }
    if let Some(n) = f["statement"]["value_max_chars"].as_u64() {
        out.push_str(&format!("Each line is read up to {n} characters.\n"));
    }
    out.push_str("Product needs a business Eustress has verified. A missing line is \"Qualification Statement missing\"; a line the Space disproves is B9 and is not listed. The statement is shown with the listing, so write it for visitors.\n");
    out.push_str(&format!(
        "\nFiction: the tag \"{}\" plus a genre tag ({}; any tag ending in {} also counts), and Category: Fiction.\n",
        f["fiction"]["tag"].as_str().unwrap_or("fiction"),
        string_list(&f["fiction"]["genre_tags"]).join(", "),
        string_list(&f["fiction"]["genre_suffixes"]).join(" or "),
    ));
    if let Some(part) = code_part("part iii").into_iter().next() {
        out.push_str("\nThe Code's own words (Part III):\n\n");
        out.push_str(&part);
        out.push('\n');
    }
    out
}

fn string_list(v: &Value) -> Vec<String> {
    v.as_array().map(|a| a.iter().filter_map(|x| x.as_str().map(String::from)).collect()).unwrap_or_default()
}

/// The text of `judge_guide` for one topic, or why there is none.
fn guide_text(topic: &str) -> Result<String, String> {
    let f = findings()?;
    let t = topic.trim();
    let lower = t.to_ascii_lowercase();
    let body = match lower.as_str() {
        "" | "overview" => skill_section("## 2.").ok_or("the skill has no section 2")?,
        "review" => {
            let mut s = skill_section("## 4.").ok_or("the skill has no section 4")?;
            s.push_str(
                "\n\nNote for an agent using these tools: `judge_verdict` replaces running scripts/verdict.mjs in Step 5. \
                 Write your Part VII judge answer as a JSON object after reading every script and the scene (Step 3), \
                 then pass it as `judge`; the Eustress API runs the same live verdict rules and returns the findings Studio would show. \
                 `judge_check_listing` covers the deterministic listing checks of Step 2. `judge_guide` topic \"code\" gives you the Code to score against, \
                 and Part VII is the exact shape of the judge answer.",
            );
            s
        }
        "statement" => statement_topic(&f),
        "code" => normalized(CODE_MD),
        _ => {
            let upper = t.to_ascii_uppercase();
            let blocks = if is_article_id(t) {
                code_article(&upper)
            } else if lower.starts_with("part ") {
                code_part(&lower)
            } else {
                Vec::new()
            };
            if blocks.is_empty() {
                return Err(format!(
                    "No topic or article \"{t}\". Topics: overview, review, statement, code; or an article or test id such as B3, B6, T4, A1; or a Part such as \"Part IX\"."
                ));
            }
            blocks.join("\n\n")
        }
    };
    Ok(format!("Guardian Code v{}. {DISCLAIMER}\n\n{body}", policy_version(&f)))
}

