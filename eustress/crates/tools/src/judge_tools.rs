#[derive(Debug, Clone, Default)]
struct Statement {
    category: Option<String>,
    objective: Option<String>,
    lesson: Option<String>,
    real_world_link: Option<String>,
    missing: Vec<&'static str>,
    category_not_in_list: bool,
}

impl Statement {
    fn present(&self) -> bool {
        self.missing.is_empty()
    }
}

fn is_blank(c: char) -> bool {
    c == ' ' || c == '\t'
}

/// One statement line: a label at the start of the line (any case), optional
/// blanks, a colon, then the value. Same rule as the review's STATEMENT_LINE.
fn statement_line(line: &str) -> Option<(&'static str, String)> {
    let t = line.trim_start_matches(is_blank);
    let lower = t.to_ascii_lowercase();
    for (label, key) in [
        ("category", "category"),
        ("objective", "objective"),
        ("lesson", "lesson"),
        ("real-world link", "real_world_link"),
        ("real world link", "real_world_link"),
    ] {
        if let Some(rest) = lower.strip_prefix(label) {
            let after = rest.trim_start_matches(is_blank);
            if after.starts_with(':') {
                // ASCII lowercasing keeps byte offsets, so the colon sits at the same place in `t`.
                let colon = t.len() - after.len();
                let value = t[colon + 1..].trim_matches(is_blank).to_string();
                return Some((key, value));
            }
        }
    }
    None
}

/// The Qualification Statement the way the review's extractQualificationStatement reads it:
/// the first line with each label counts; present only when all four have text and the
/// Category is on the list (a trailing period is ignored).
fn extract_statement(description: &str, categories: &[String], value_max: usize) -> Statement {
    let text = description.replace("\r\n", "\n").replace('\r', "\n");
    let mut found: std::collections::BTreeMap<&'static str, String> = std::collections::BTreeMap::new();
    for line in text.split('\n') {
        if let Some((key, value)) = statement_line(line) {
            found.entry(key).or_insert(value);
        }
    }
    let mut out = Statement::default();
    let named = found.get("category").map(|c| c.trim_end_matches('.').trim().to_ascii_lowercase());
    if let Some(named) = &named {
        out.category = categories.iter().find(|c| c.to_ascii_lowercase() == *named).cloned();
        out.category_not_in_list = out.category.is_none();
    }
    if out.category.is_none() {
        out.missing.push("Category");
    }
    for (key, label) in [("objective", "Objective"), ("lesson", "Lesson"), ("real_world_link", "Real-world link")] {
        let value = found.get(key).cloned().unwrap_or_default();
        if value.is_empty() {
            out.missing.push(label);
        } else {
            let clipped: String = value.chars().take(value_max).collect();
            match key {
                "objective" => out.objective = Some(clipped),
                "lesson" => out.lesson = Some(clipped),
                _ => out.real_world_link = Some(clipped),
            }
        }
    }
    out
}

fn statement_json(s: &Statement) -> Value {
    json!({
        "present": s.present(),
        "category": s.category,
        "objective": s.objective,
        "lesson": s.lesson,
        "real_world_link": s.real_world_link,
        "missing": s.missing,
        "category_not_in_list": s.category_not_in_list,
    })
}

fn tag_shape_ok(tag: &str) -> bool {
    // ^[a-z0-9]+(?:-[a-z0-9]+)*$
    if tag.is_empty() {
        return false;
    }
    tag.split('-').all(|part| !part.is_empty() && part.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit()))
}

/// The tag `fiction` plus a genre tag (a listed genre, or one ending in `-fiction` or `-fi`).
fn fiction_labelled(tags: &[String], f: &Value) -> bool {
    let fiction_tag = f["fiction"]["tag"].as_str().unwrap_or("fiction");
    if !tags.iter().any(|t| t.as_str() == fiction_tag) {
        return false;
    }
    let genres = string_list(&f["fiction"]["genre_tags"]);
    let suffixes = string_list(&f["fiction"]["genre_suffixes"]);
    tags.iter().any(|t| {
        t.as_str() != fiction_tag && (genres.iter().any(|g| g == t) || suffixes.iter().any(|s| t.ends_with(s.as_str())))
    })
}

fn is_word_byte(b: u8) -> bool {
    b.is_ascii_alphanumeric() || b == b'_'
}

/// `word` as a whole word in already-lowercased `lower`.
fn has_word(lower: &str, word: &str) -> bool {
    let bytes = lower.as_bytes();
    let mut from = 0usize;
    while let Some(pos) = lower[from..].find(word) {
        let start = from + pos;
        let end = start + word.len();
        let before = start == 0 || !is_word_byte(bytes[start - 1]);
        let after = end >= bytes.len() || !is_word_byte(bytes[end]);
        if before && after {
            return true;
        }
        from = end;
    }
    false
}

/// Code B1(c): the listing or its tags sell it as horror or a jumpscare game.
fn horror_terms(name: &str, description: &str, tags: &[String]) -> Vec<&'static str> {
    let mut text = format!("{name}\n{description}");
    for t in tags {
        text.push('\n');
        text.push_str(t);
    }
    let lower = text.to_ascii_lowercase();
    ["horror", "jumpscare", "jump scare"].into_iter().filter(|w| has_word(&lower, w)).collect()
}

fn find_urls(text: &str) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    for tok in text.split(|c: char| c.is_whitespace() || matches!(c, '<' | '>' | '"' | '\'' | '(' | ')' | '[' | ']')) {
        let lower = tok.to_ascii_lowercase();
        if lower.starts_with("http://") || lower.starts_with("https://") || lower.starts_with("www.") {
            let trimmed = tok.trim_end_matches(|c: char| matches!(c, '.' | ',' | ';' | ':' | '!' | '?')).to_string();
            if !trimmed.is_empty() && !out.contains(&trimmed) {
                out.push(trimmed);
            }
        }
    }
    out
}

const PAYMENT_DOMAINS: [&str; 6] = ["ko-fi.com", "patreon.com", "paypal.me", "buymeacoffee.com", "cash.app", "venmo.com"];
const SHORTENERS: [&str; 7] = ["bit.ly", "tinyurl.com", "t.co", "goo.gl", "is.gd", "ow.ly", "cutt.ly"];

/// What about a URL the link review (Code Part IX) would object to or the author should know.
fn url_notes(url: &str) -> Vec<String> {
    let mut notes = Vec::new();
    let lower = url.to_ascii_lowercase();
    if lower.starts_with("http://") {
        notes.push("use https://".to_string());
    }
    let rest = lower.trim_start_matches("https://").trim_start_matches("http://");
    let host = rest.split(|c: char| matches!(c, '/' | '?' | '#')).next().unwrap_or("");
    if host.contains(':') {
        notes.push("has a port; use the plain address of the destination".to_string());
    }
    let bare = host.split(':').next().unwrap_or("");
    if !bare.is_empty() && bare.chars().all(|c| c.is_ascii_digit() || c == '.') {
        notes.push("an IP address; use the destination's own domain".to_string());
    }
    if SHORTENERS.iter().any(|s| bare == *s) {
        notes.push("a link shortener; use the destination itself".to_string());
    }
    if PAYMENT_DOMAINS.iter().any(|d| bare == *d || bare.ends_with(&format!(".{d}"))) {
        notes.push("a payment or donation page: allowed once the link review passes it (Code B6(h), Part IX)".to_string());
    }
    notes
}

const BASE58: &str = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz";

fn looks_like_crypto_address(tok: &str) -> bool {
    // Ethereum: 0x then 40 hex digits.
    if tok.len() == 42 && tok.starts_with("0x") && tok[2..].chars().all(|c| c.is_ascii_hexdigit()) {
        return true;
    }
    // Bitcoin bech32: bc1 then 11 to 71 of the bech32 alphabet.
    if tok.starts_with("bc1")
        && tok.len() >= 14
        && tok.len() <= 74
        && tok[3..].chars().all(|c| matches!(c, 'a' | 'c'..='h' | 'j'..='n' | 'p'..='z' | '0' | '2'..='9'))
    {
        return true;
    }
    // Bitcoin base58: a leading 1 or 3, 26 to 35 characters in all; a run of letters alone is not one.
    if (tok.starts_with('1') || tok.starts_with('3')) && tok.len() >= 26 && tok.len() <= 35 && tok.chars().all(|c| BASE58.contains(c)) {
        let rest = &tok[1..];
        return rest.chars().any(|c| c.is_ascii_digit()) && rest.chars().any(|c| c.is_ascii_alphabetic());
    }
    false
}

fn has_crypto_address(text: &str) -> Option<String> {
    text.split(|c: char| !c.is_ascii_alphanumeric())
        .find(|tok| looks_like_crypto_address(tok))
        .map(|t| t.to_string())
}

fn mentions_money(text: &str) -> bool {
    let chars: Vec<char> = text.chars().collect();
    for (i, c) in chars.iter().enumerate() {
        if matches!(c, '$' | '€' | '£') {
            let next = chars[i + 1..].iter().find(|x| !x.is_whitespace());
            if next.map_or(false, |x| x.is_ascii_digit()) {
                return true;
            }
        }
    }
    let lower = text.to_ascii_lowercase();
    let words: Vec<&str> = lower.split(|c: char| !c.is_ascii_alphanumeric()).filter(|w| !w.is_empty()).collect();
    for (i, w) in words.iter().enumerate() {
        if matches!(*w, "buy" | "purchase" | "pay" | "paid" | "sell" | "sold" | "price" | "venmo" | "paypal" | "cashapp") || w.starts_with("donat") {
            return true;
        }
        if w.chars().all(|c| c.is_ascii_digit()) {
            if let Some(next) = words.get(i + 1) {
                if matches!(*next, "usd" | "eur" | "gbp" | "dollar" | "dollars" | "euro" | "euros" | "pound" | "pounds") {
                    return true;
                }
            }
        }
    }
    false
}

/// Code B6(h): an unlock, access, activation, premium or VIP code or key, offered for money.
fn paid_unlock_code(text: &str) -> bool {
    let lower = text.to_ascii_lowercase();
    let words: Vec<&str> = lower.split(|c: char| !c.is_ascii_alphanumeric()).filter(|w| !w.is_empty()).collect();
    let named = words.windows(2).any(|p| {
        matches!(p[0], "unlock" | "access" | "activation" | "premium" | "vip") && matches!(p[1], "code" | "codes" | "key" | "keys")
    });
    named && mentions_money(text)
}

fn finding(severity: &str, code: &str, title: &str, why: &str, what_to_change: &str) -> Value {
    json!({ "severity": severity, "code": code, "title": title, "why": why, "what_to_change": what_to_change })
}

/// A finding from the review's own author copy (findings.json `author_copy.<key>`).
fn copy_finding(f: &Value, key: &str, severity: &str, extra_why: Option<String>) -> Value {
    let c = &f["author_copy"][key];
    let mut why = c["why"].as_str().unwrap_or("").to_string();
    if let Some(extra) = extra_why {
        if !why.is_empty() {
            why.push(' ');
        }
        why.push_str(&extra);
    }
    finding(
        severity,
        key,
        c["title"].as_str().unwrap_or(key),
        &why,
        c["what_to_change"].as_str().unwrap_or(""),
    )
}

fn statement_skeleton(s: &Statement, categories: &[String]) -> String {
    let mut lines = Vec::new();
    lines.push(match &s.category {
        Some(c) => format!("Category: {c}"),
        None => format!("Category: <one of {}>", categories.join(" | ")),
    });
    lines.push(format!("Objective: {}", s.objective.clone().unwrap_or_else(|| "<one sentence: what a visitor does here>".into())));
    lines.push(format!("Lesson: {}", s.lesson.clone().unwrap_or_else(|| "<one sentence: the specific skill, concept or method, present in the Space>".into())));
    lines.push(format!(
        "Real-world link: {}",
        s.real_world_link.clone().unwrap_or_else(|| "<one sentence: the real place, system, data, skill or problem, named>".into())
    ));
    lines.join("\n")
}

/// Every deterministic check on a listing. Returns the findings and the extracted statement.
fn check_listing(f: &Value, name: &str, description: &str, tags: &[String]) -> (Vec<Value>, Statement) {
    let categories = string_list(&f["statement"]["categories"]);
    let value_max = f["statement"]["value_max_chars"].as_u64().unwrap_or(300) as usize;
    let statement = extract_statement(description, &categories, value_max);
    let mut out: Vec<Value> = Vec::new();

    // Qualification Statement (Code Part III).
    if !statement.present() {
        let mut extra = format!("Missing: {}.", statement.missing.join(", "));
        if statement.category_not_in_list {
            extra.push_str(&format!(" The Category line names something that is not on the list ({}).", categories.join(", ")));
        }
        let mut v = copy_finding(f, "statement_missing", "fix", Some(extra));
        v["suggested_statement"] = json!(statement_skeleton(&statement, &categories));
        out.push(v);
    }

    // Fiction label (Code Part III).
    let is_fiction_category = statement.category.as_deref() == Some("Fiction");
    if is_fiction_category && !fiction_labelled(tags, f) {
        out.push(copy_finding(f, "fiction_label_missing", "fix", None));
    }
    let fiction_tag = f["fiction"]["tag"].as_str().unwrap_or("fiction");
    if !is_fiction_category && tags.iter().any(|t| t.as_str() == fiction_tag) && statement.category.is_some() {
        out.push(finding(
            "note",
            "fiction_category_mismatch",
            "Fiction tag without Category: Fiction (Code Part III)",
            "The tag \"fiction\" says the Space is fiction, and the Category line says otherwise.",
            "Set the Category line to Fiction, or remove the fiction tag if the Space is not fiction.",
        ));
    }

    // Tags: count and shape.
    let max_tags = f["tags"]["max_author_tags"].as_u64().unwrap_or(8) as usize;
    if tags.len() > max_tags {
        out.push(finding(
            "fix",
            "tags_too_many",
            "Too many tags (Code Part III)",
            &format!("A listing carries at most {max_tags} tags; this one has {}.", tags.len()),
            &format!("Keep the {max_tags} tags that best say what the Space contains, or leave tags empty and the review chooses up to {}.", f["tags"]["max_review_tags"].as_u64().unwrap_or(5)),
        ));
    }
    let bad_tags: Vec<&String> = tags.iter().filter(|t| !tag_shape_ok(t)).collect();
    if !bad_tags.is_empty() {
        let list: Vec<String> = bad_tags.iter().map(|t| format!("\"{t}\"")).collect();
        out.push(finding(
            "fix",
            "tags_shape",
            "Tag shape (Code Part III)",
            &format!(
                "Tags are lowercase letters, digits and single hyphens (pattern {}). These are not: {}.",
                f["tags"]["shape"].as_str().unwrap_or("^[a-z0-9]+(?:-[a-z0-9]+)*$"),
                list.join(", ")
            ),
            "Rewrite each as lowercase words joined by single hyphens, with no phone number, email or handle.",
        ));
    }
    if tags.is_empty() {
        out.push(finding(
            "note",
            "tags_empty",
            "No tags",
            "With no tags, the review chooses up to its own limit from what it sees.",
            "Add tags that describe what the Space contains if you want to choose them yourself.",
        ));
    }

    // Lengths.
    let name_len = name.chars().count();
    if name_len > NAME_MAX {
        out.push(finding("fix", "name_too_long", "Name too long", &format!("The name is {name_len} characters; the limit is {NAME_MAX}."), "Shorten the name."));
    }
    if name.trim().is_empty() {
        out.push(finding("fix", "name_missing", "No name", "A listing needs a name.", "Give the listing a name that says what the Space is."));
    }
    let desc_len = description.chars().count();
    if desc_len > DESCRIPTION_MAX {
        out.push(finding(
            "fix",
            "description_too_long",
            "Description too long",
            &format!("The description is {desc_len} characters; the limit is {DESCRIPTION_MAX}."),
            "Shorten the description; keep the four statement lines.",
        ));
    }

    // Horror words (Code B1(c)).
    let horror = horror_terms(name, description, tags);
    if !horror.is_empty() {
        out.push(copy_finding(f, "code_B1", "fix", Some(format!("The listing says: {}. Selling a Space as horror or a jumpscare game is itself B1(c); \"spooky\", \"creepy\" and \"haunted\" are mild fright and are fine.", horror.join(", ")))));
    }

    // URLs (Code Part IX).
    let urls = find_urls(description);
    if !urls.is_empty() {
        let rows: Vec<String> = urls
            .iter()
            .map(|u| {
                let notes = url_notes(u);
                if notes.is_empty() {
                    u.clone()
                } else {
                    format!("{u} ({})", notes.join("; "))
                }
            })
            .collect();
        out.push(finding(
            "note",
            "links_in_description",
            "Links in the description (Code Part IX)",
            &format!(
                "Each URL is link-reviewed before it is shown: it reads \"[link pending review]\" until the review approves it, and \"[link removed]\" if the review removes it. Found: {}.",
                rows.join(" | ")
            ),
            "Use plain https:// links to the destination itself (no shorteners, redirects, IP addresses or ports). Link labels are plain text with no URL.",
        ));
    }

    // Crypto addresses and paid unlock codes (Code B6(h)).
    let all_text = format!("{name}\n{description}\n{}", tags.join("\n"));
    if let Some(addr) = has_crypto_address(&all_text) {
        out.push(copy_finding(f, "code_B6", "fix", Some(format!("A cryptocurrency address is in the listing (\"{addr}\"); no link review can clear it (B6(h))."))));
    }
    if paid_unlock_code(&all_text) {
        out.push(copy_finding(f, "code_B6", "fix", Some("The listing offers an unlock, access or premium code or key for money, sold off Eustress (B6(h)).".to_string())));
    }

    (out, statement)
}

fn render_check(f: &Value, listing: &Listing, findings_list: &[Value], statement: &Statement) -> String {
    let categories = string_list(&f["statement"]["categories"]);
    let mut lines: Vec<String> = Vec::new();
    lines.push(format!("Guardian Code v{}. {DISCLAIMER}", policy_version(f)));
    lines.push(String::new());
    lines.push(format!("Listing checked: name \"{}\", {} character description, {} tag(s) [{}].", listing.name, listing.description.chars().count(), listing.tags.len(), listing.tags.join(", ")));
    if !listing.sources.is_empty() {
        lines.push(format!("Read from: {}.", listing.sources.join("; ")));
    }
    lines.push(String::new());
    if statement.present() {
        lines.push("Qualification Statement found:".to_string());
        lines.push(format!("  Category: {}", statement.category.clone().unwrap_or_default()));
        lines.push(format!("  Objective: {}", statement.objective.clone().unwrap_or_default()));
        lines.push(format!("  Lesson: {}", statement.lesson.clone().unwrap_or_default()));
        lines.push(format!("  Real-world link: {}", statement.real_world_link.clone().unwrap_or_default()));
    } else {
        lines.push(format!("Qualification Statement missing: {}.", statement.missing.join(", ")));
    }
    lines.push(String::new());
    let fixes = findings_list.iter().filter(|v| v["severity"] == "fix").count();
    if findings_list.is_empty() {
        lines.push("No deterministic findings.".to_string());
    } else {
        lines.push(format!("{} finding(s), {} to fix:", findings_list.len(), fixes));
        for v in findings_list {
            lines.push(format!("  [{}] {}", v["severity"].as_str().unwrap_or("?"), v["title"].as_str().unwrap_or("?")));
            if let Some(w) = v["why"].as_str().filter(|s| !s.is_empty()) {
                lines.push(format!("    Why: {w}"));
            }
            if let Some(w) = v["what_to_change"].as_str().filter(|s| !s.is_empty()) {
                lines.push(format!("    What to change: {w}"));
            }
        }
    }
    if !statement.present() {
        lines.push(String::new());
        lines.push("Suggested statement skeleton (fill in what is true of the Space; if the Lesson or Real-world link cannot be written honestly, change the idea, not the wording):".to_string());
        for l in statement_skeleton(statement, &categories).lines() {
            lines.push(format!("  {l}"));
        }
    }
    lines.push(String::new());
    lines.push(
        "These are the deterministic checks only. They cannot score the tests T1 to T4 or cite an article: those need your own reading of every script and the scene (judge_guide topic \"review\") and then judge_verdict."
            .to_string(),
    );
    lines.join("\n")
}

// ---------------------------------------------------------------------------
// Rendering a verdict (the skill's scripts/verdict.mjs render())
// ---------------------------------------------------------------------------

fn render_verdict(result: &Value) -> String {
    let v = &result["view"];
    let mut lines: Vec<String> = vec![
        format!(
            "EMULATED REVIEW under Guardian Code v{}. The real review decides; passing this is not approval.",
            result["policy_version"].as_str().map(String::from).unwrap_or_else(|| result["policy_version"].to_string())
        ),
        String::new(),
        format!("Status: {}", v["status"].as_str().unwrap_or("?")),
        v["headline"].as_str().unwrap_or("").to_string(),
    ];
    if let Some(reasons) = v["reasons"].as_array() {
        for r in reasons {
            lines.push(format!("  {}", r["title"].as_str().unwrap_or("?")));
            if let Some(w) = r["why"].as_str().filter(|s| !s.is_empty()) {
                lines.push(format!("    Why: {w}"));
            }
            if let Some(w) = r["what_to_change"].as_str().filter(|s| !s.is_empty()) {
                lines.push(format!("    What to change: {w}"));
            }
        }
    }
    if let Some(e) = v["suggested_edit"].as_str().filter(|s| !s.is_empty()) {
        lines.push(format!("  Suggested edit: {e}"));
    }
    if let Some(t) = v["suggested_statement"]["text"].as_str().filter(|s| !s.is_empty()) {
        lines.push(String::new());
        lines.push("Suggested statement (paste into the description):".to_string());
        for l in t.split('\n') {
            lines.push(format!("  {l}"));
        }
    }
    if let Some(t) = v["tags_chosen"].as_str().filter(|s| !s.is_empty()) {
        lines.push(String::new());
        lines.push(t.to_string());
    }
    if let Some(r) = v["rating_label"].as_str().filter(|s| !s.is_empty()).or_else(|| v["rating"].as_str().filter(|s| !s.is_empty())) {
        let descriptors = string_list(&v["descriptors"]);
        lines.push(String::new());
        if descriptors.is_empty() {
            lines.push(format!("Rating: {r}"));
        } else {
            lines.push(format!("Rating: {r} ({})", descriptors.join(", ")));
        }
    }
    let s = &result["statement"];
    if s.is_object() {
        lines.push(String::new());
        if s["present"].as_bool() == Some(true) {
            lines.push("Qualification Statement found:".to_string());
        } else {
            let missing = string_list(&s["missing"]).join(", ");
            let note = if s["category_not_in_list"].as_bool() == Some(true) { " (the Category line names something not in the list)" } else { "" };
            lines.push(format!("Qualification Statement missing: {missing}{note}"));
        }
        if let Some(c) = s["category"].as_str() {
            lines.push(format!("  Category: {c}"));
        }
        for (k, label) in [("objective", "Objective"), ("lesson", "Lesson"), ("real_world_link", "Real-world link")] {
            if let Some(t) = s[k].as_str() {
                lines.push(format!("  {label}: {t}"));
            }
        }
    }
    lines.push(String::new());
    lines.push("Rule trail (Code Part IV, for you; Studio does not show it):".to_string());
    let trail = result["trail"].as_array().cloned().unwrap_or_default();
    for t in &trail {
        let rule = if t["rule"].is_null() { "-".to_string() } else { t["rule"].to_string().trim_matches('"').to_string() };
        let article = t["article"].as_str().map(|a| format!(" {a}")).unwrap_or_default();
        let test = match (t["test"].as_str(), t.get("score")) {
            (Some(name), Some(score)) => format!(" {name}={}", score.to_string().trim_matches('"')),
            _ => String::new(),
        };
        lines.push(format!(
            "  rule {rule}: {}{article}{test} -> {}",
            t["code"].as_str().unwrap_or("?"),
            t["action"].as_str().unwrap_or("?")
        ));
    }
    if trail.is_empty() {
        lines.push("  every test at 2 or above and the statement matches -> listed (rule 8)".to_string());
    }
    lines.join("\n")
}

/// Why a verdict request failed, in words an agent can act on.
fn verdict_failure(code: u16, body: &Value, retry_after: Option<String>) -> String {
    match code {
        422 => format!(
            "The judge answer is malformed ({}). The live review would ask once more; fix the answer so it matches the Code's Part VII exactly (judge_guide topic \"Part VII\") and call judge_verdict again.",
            body["detail"].as_str().unwrap_or("no detail given")
        ),
        429 => format!(
            "The emulation endpoint is rate limited (HTTP 429){}. Wait and call judge_verdict again; nothing was lost.",
            retry_after.map(|r| format!(", retry after {r} seconds")).unwrap_or_default()
        ),
        _ => format!("The emulation endpoint refused the request (HTTP {code}): {}", body["error"].as_str().unwrap_or("no reason given")),
    }
}

