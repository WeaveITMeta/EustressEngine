#[derive(Debug, Clone, Default)]
struct Listing {
    name: String,
    description: String,
    tags: Vec<String>,
    is_public: bool,
    /// Where each part came from, for the report.
    sources: Vec<String>,
}

struct FileListing {
    name: Option<String>,
    description: Option<String>,
    tags: Option<Vec<String>>,
    is_public: Option<bool>,
}

/// The `[listing]` of a publish.toml, parsed with the toml crate (a description
/// carries escaped line ends that a hand parse turns into a literal backslash).
fn read_publish_listing(path: &Path) -> Option<FileListing> {
    let text = std::fs::read_to_string(path).ok()?;
    let doc: toml::Value = text.parse().ok()?;
    let listing = doc.get("listing")?.as_table()?;
    Some(FileListing {
        name: listing.get("name").and_then(|v| v.as_str()).map(String::from),
        description: listing.get("description").and_then(|v| v.as_str()).map(String::from),
        tags: listing.get("tags").and_then(|v| v.as_array()).map(|a| a.iter().filter_map(|t| t.as_str().map(String::from)).collect()),
        is_public: doc.get("visibility").and_then(|v| v.get("is_public")).and_then(|v| v.as_bool()),
    })
}

/// The listing an agent means: each field from `args` when given, else from the
/// Universe's `.eustress/publish.toml`, else the Space's own.
fn resolve_listing(args: &Value, listing_arg: Option<&Value>, ctx: &ToolContext) -> Listing {
    let src = listing_arg.filter(|v| v.is_object()).unwrap_or(args);
    let universe_file = read_publish_listing(&ctx.universe_root.join(".eustress").join("publish.toml"));
    let space_file = read_publish_listing(&ctx.space_root.join(".eustress").join("publish.toml"));
    let mut out = Listing { is_public: true, ..Default::default() };

    match src.get("name").and_then(|v| v.as_str()) {
        Some(s) => {
            out.name = s.to_string();
            out.sources.push("name: argument".into());
        }
        None => {
            if let Some(s) = universe_file.as_ref().and_then(|l| l.name.clone()) {
                out.name = s;
                out.sources.push("name: Universe .eustress/publish.toml".into());
            } else if let Some(s) = space_file.as_ref().and_then(|l| l.name.clone()) {
                out.name = s;
                out.sources.push("name: Space .eustress/publish.toml".into());
            }
        }
    }
    match src.get("description").and_then(|v| v.as_str()) {
        Some(s) => {
            out.description = s.to_string();
            out.sources.push("description: argument".into());
        }
        None => {
            if let Some(s) = universe_file.as_ref().and_then(|l| l.description.clone()) {
                out.description = s;
                out.sources.push("description: Universe .eustress/publish.toml".into());
            } else if let Some(s) = space_file.as_ref().and_then(|l| l.description.clone()) {
                out.description = s;
                out.sources.push("description: Space .eustress/publish.toml".into());
            }
        }
    }
    match src.get("tags").and_then(|v| v.as_array()) {
        Some(a) => {
            out.tags = a.iter().filter_map(|t| t.as_str().map(String::from)).collect();
            out.sources.push("tags: argument".into());
        }
        None => {
            if let Some(t) = universe_file.as_ref().and_then(|l| l.tags.clone()) {
                out.tags = t;
                out.sources.push("tags: Universe .eustress/publish.toml".into());
            } else if let Some(t) = space_file.as_ref().and_then(|l| l.tags.clone()) {
                out.tags = t;
                out.sources.push("tags: Space .eustress/publish.toml".into());
            }
        }
    }
    if let Some(b) = src.get("is_public").and_then(|v| v.as_bool()) {
        out.is_public = b;
    } else if let Some(b) = universe_file.as_ref().and_then(|l| l.is_public).or_else(|| space_file.as_ref().and_then(|l| l.is_public)) {
        out.is_public = b;
    }
    out
}

