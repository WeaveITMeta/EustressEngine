pub struct JudgeVerdictTool;

impl ToolHandler for JudgeVerdictTool {
    fn definition(&self) -> ToolDefinition {
        ToolDefinition {
            name: "judge_verdict",
            description: "Run the live Guardian Code verdict rules on YOUR judge answer, BEFORE PUBLISHING. First read the Space the way the real review does (judge_guide topic \"review\": every script in every Space in full, the scene, the captures), score the four tests and cite the articles, and write the Code's Part VII judge answer as a JSON object. Pass it as `judge`. The Eustress API applies the same rules the real review uses and returns what Studio would show: the outcome (listed, changes requested, not listed), each finding's title, Why and What to change, a suggested edit and statement, the chosen tags and the rating. The listing defaults to the saved one (the Universe's .eustress/publish.toml). Sends the listing and your answer to the Eustress API (network); it publishes nothing and changes nothing. The result is an emulation: the real review decides and passing is not approval.",
            input_schema: json!({
                "type": "object",
                "properties": {
                    "judge": { "type": "object", "description": "Your own judge answer, the JSON object of the Code's Part VII, written after reading the Space (judge_guide topic \"Part VII\" gives its shape)." },
                    "listing": {
                        "type": "object",
                        "description": "The listing as it will be published. Default: the saved listing.",
                        "properties": {
                            "name": { "type": "string" },
                            "description": { "type": "string" },
                            "tags": { "type": "array", "items": { "type": "string" } },
                            "is_public": { "type": "boolean" }
                        }
                    },
                    "dossier": { "type": "object", "description": "Optional: the digest from <Universe>/.eustress/moderation-dossier.json (the last publish's), when you have read it." }
                },
                "required": ["judge"]
            }),
            modes: &[WorkshopMode::General],
            requires_approval: false,
            stream_topics: &[],
        }
    }

    fn execute(&self, input: Value, ctx: &ToolContext) -> ToolResult {
        // The judge answer may arrive as an object or, from a client that stringifies, as JSON text.
        let judge = match input.get("judge") {
            Some(v) if v.is_object() => v.clone(),
            Some(Value::String(s)) => match serde_json::from_str::<Value>(s) {
                Ok(v) if v.is_object() => v,
                _ => return err("judge_verdict", "judge must be a JSON object (the Code's Part VII judge answer); the string given does not parse as one."),
            },
            _ => return err("judge_verdict", "Missing required parameter: judge (your Part VII judge answer, a JSON object). Read the Space first: judge_guide topic \"review\"."),
        };
        let listing = resolve_listing(&input, input.get("listing"), ctx);
        if listing.sources.is_empty() {
            return err(
                "judge_verdict",
                "No listing: pass listing {name, description, tags, is_public}, or save the listing first (Studio's Publish dialog writes <Universe>/.eustress/publish.toml).",
            );
        }
        let dossier = input.get("dossier").cloned().filter(|v| v.is_object()).unwrap_or(Value::Null);
        let body = json!({
            "listing": { "name": listing.name, "description": listing.description, "tags": listing.tags, "is_public": listing.is_public },
            "judge": judge,
            "dossier": dossier,
        });
        let url = format!("{}/api/moderation/emulate", api_base());
        let result = ureq::post(&url)
            .timeout(std::time::Duration::from_secs(60))
            .set("Content-Type", "application/json")
            .send_string(&body.to_string());
        match result {
            Ok(resp) => match resp.into_json::<Value>() {
                Ok(v) if v["view"].is_object() => {
                    let text = render_verdict(&v);
                    ok("judge_verdict", text, v)
                }
                Ok(v) => err("judge_verdict", format!("The emulation endpoint answered without a view: {}", v.to_string().chars().take(500).collect::<String>())),
                Err(e) => err("judge_verdict", format!("The emulation endpoint answered with bad JSON: {e}")),
            },
            Err(ureq::Error::Status(code, resp)) => {
                let retry = resp.header("Retry-After").map(String::from);
                let body = resp.into_json::<Value>().unwrap_or_else(|_| json!({ "error": format!("HTTP {code}") }));
                err("judge_verdict", verdict_failure(code, &body, retry))
            }
            Err(e) => err("judge_verdict", format!("Could not reach {url}: {e}. Nothing was sent that could be lost; try again when the network is back.")),
        }
    }
}

