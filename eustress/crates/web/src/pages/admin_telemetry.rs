#[derive(Clone, Debug, Default, PartialEq, Deserialize)]
struct ToolCount {
    id: String,
    clicks: i64,
    installs: i64,
    /// Epoch ms of the most recent session that touched this tool (0 = unknown).
    /// Derived server-side from the recent-session feed, not a per-tool counter.
    #[serde(default)]
    last: f64,
}

#[derive(Clone, Debug, Default, PartialEq, Deserialize)]
struct CommentRow {
    ts: f64,
    #[serde(default)]
    tool: String,
    text: String,
    #[serde(default)]
    install: String,
}

/// One engine session's aggregate, newest-first. `#[serde(default)]` throughout
/// so the page keeps working if it deploys ahead of the Worker.
#[derive(Clone, Debug, Default, PartialEq, Deserialize)]
struct RecentSession {
    #[serde(default)]
    ts: f64,
    #[serde(default)]
    install: String,
    #[serde(default)]
    mode: String,
    #[serde(default)]
    version: String,
    #[serde(default)]
    tools: Vec<(String, i64)>,
    #[serde(default)]
    total: i64,
}

#[derive(Clone, Debug, Default, PartialEq, Deserialize)]
struct DayCount {
    date: String,
    count: i64,
}

#[derive(Clone, Debug, Default, PartialEq, Deserialize)]
struct Summary {
    generated_at: String,
    enabled: bool,
    tools: Vec<ToolCount>,
    comments: Vec<CommentRow>,
    #[serde(default)]
    recent: Vec<RecentSession>,
    sessions_by_day: Vec<DayCount>,
}

