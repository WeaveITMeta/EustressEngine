/// 12345 -> "12,345". Tabular numerals plus grouping keeps the stat row scannable.
fn thousands(n: i64) -> String {
    let s = n.abs().to_string();
    let mut out = String::with_capacity(s.len() + s.len() / 3);
    for (i, c) in s.chars().enumerate() {
        if i > 0 && (s.len() - i) % 3 == 0 {
            out.push(',');
        }
        out.push(c);
    }
    if n < 0 {
        format!("-{out}")
    } else {
        out
    }
}

fn now_ms() -> f64 {
    js_sys::Date::now()
}

/// "just now" / "14m ago" / "3h ago" / "2d ago" — absolute dates live in the
/// copied brief, where they survive being pasted somewhere else.
fn rel_time(ts_ms: f64, now: f64) -> String {
    if ts_ms <= 0.0 {
        return String::new();
    }
    let secs = ((now - ts_ms) / 1000.0).max(0.0);
    if secs < 90.0 {
        "just now".to_string()
    } else if secs < 3600.0 {
        format!("{}m ago", (secs / 60.0).round() as i64)
    } else if secs < 86400.0 {
        format!("{}h ago", (secs / 3600.0).round() as i64)
    } else if secs < 86400.0 * 30.0 {
        format!("{}d ago", (secs / 86400.0).round() as i64)
    } else {
        format!("{}mo ago", (secs / (86400.0 * 30.0)).round() as i64)
    }
}

/// UTC date stamp for copied briefs (`2026-07-24 15:03`).
fn stamp(ts_ms: f64) -> String {
    if ts_ms <= 0.0 {
        return "unknown".to_string();
    }
    let d = js_sys::Date::new(&wasm_bindgen::JsValue::from_f64(ts_ms));
    let iso = String::from(d.to_iso_string());
    iso.get(0..16).map(|s| s.replace('T', " ")).unwrap_or(iso)
}

