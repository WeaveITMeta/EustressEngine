struct BriefInput<'a> {
    id: &'a str,
    label: &'a str,
    tooltip: &'a str,
    wired: bool,
    path: &'a str,
    clicks: i64,
    installs: i64,
    last: f64,
    comments: &'a [CommentRow],
}

fn feature_brief(b: BriefInput<'_>) -> String {
    let mut s = String::new();
    s.push_str(&format!("# Feature request — {} (`{}`)\n\n", b.label, b.id));
    s.push_str(&format!(
        "Lives at      : {}\nIn-app promise: \"{}\"\n",
        if b.path.is_empty() { "(not in the shipped hierarchy)" } else { b.path },
        b.tooltip
    ));
    s.push_str(&format!(
        "Status        : {}\n",
        if b.wired {
            "WIRED — already dispatches; this is a refinement request"
        } else {
            "DREAM — no dispatch arm; clicking shows the \"on the roadmap\" toast"
        }
    ));
    s.push_str(&format!(
        "Demand        : {} click{} from {} install{}{}\n",
        b.clicks,
        if b.clicks == 1 { "" } else { "s" },
        b.installs,
        if b.installs == 1 { "" } else { "s" },
        if b.last > 0.0 {
            format!(" · last seen {}", stamp(b.last))
        } else {
            String::new()
        }
    ));

    if !b.comments.is_empty() {
        s.push_str("\n## What users actually said\n");
        for c in b.comments {
            s.push_str(&format!(
                "- \"{}\"  — install {}, {}\n",
                c.text.trim(),
                if c.install.is_empty() { "anon" } else { &c.install },
                stamp(c.ts)
            ));
        }
    }

    s.push_str("\n## To make it real\n");
    if b.wired {
        s.push_str(&format!(
            "1. Find the `\"{}\"` arm in the `SlintAction::MenuAction` match in\n   \
             eustress/crates/engine/src/ui/slint_ui.rs and extend the behaviour.\n",
            b.id
        ));
    } else {
        s.push_str(&format!(
            "1. Add a `\"{}\"` arm to the `SlintAction::MenuAction` match in\n   \
             eustress/crates/engine/src/ui/slint_ui.rs — the single dispatch choke point.\n\
             2. Add `\"{}\"` to the `WIRED` dict in scripts/gen_tool_metadata.py so the\n   \
             honest-toast path stops treating it as a dream button, then regenerate:\n     \
             python scripts/gen_tool_metadata.py\n     \
             python scripts/gen_tool_icons.py\n     \
             python scripts/gen_web_hierarchy.py\n",
            b.id, b.id
        ));
    }
    s.push_str(
        "3. Keep `cargo test -p eustress-engine --lib -- studio_modes usage_telemetry` green\n   \
         (builtins_fully_populated enforces metadata + a composed icon for every id).\n",
    );
    s
}

