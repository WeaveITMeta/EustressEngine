#[component]
pub fn AdminTelemetryPage() -> impl IntoView {
    let app_state = expect_context::<AppState>();
    let api_url = app_state.api_url.clone();
    let state = RwSignal::new(Load::Loading);

    // Tree controls.
    let query = RwSignal::new(String::new());
    let active_only = RwSignal::new(false);
    // -1 collapse all · 0 automatic (open where there's demand) · 1 expand all
    let expand = RwSignal::new(0i32);

    Effect::new(move |_| {
        let api_url = api_url.clone();
        spawn_local(async move {
            let client = ApiClient::new(&api_url);
            let summary = client.get::<Summary>("/api/telemetry/summary").await;
            match summary {
                Ok(s) => match fetch_hierarchy().await {
                    Ok(h) => state.set(Load::Ready(Box::new((s, h)))),
                    Err(e) => state.set(Load::Error(format!("hierarchy: {e}"))),
                },
                Err(ApiError::Unauthorized) => state.set(Load::Denied),
                Err(ApiError::Server { status: 403, .. }) => state.set(Load::Denied),
                Err(e) => state.set(Load::Error(e.to_string())),
            }
        });
    });

    let body = move || match state.get() {
        Load::Loading => view! {
            <div class="loading-state">
                <div class="spinner"></div>
                <p class="loading-message">"Loading tool telemetry…"</p>
            </div>
        }
        .into_any(),

        Load::Denied => view! {
            <div class="admin-denied">
                <h2>"Admin access required"</h2>
                <p>"This dashboard is restricted to the Eustress admin. Sign in with the admin identity to continue."</p>
                <a class="btn-primary" href="/login">"Sign in"</a>
            </div>
        }
        .into_any(),

        Load::Error(msg) => view! {
            <div class="alert alert-error admin-alert">
                <strong>"Couldn't load telemetry. "</strong>
                <span>{msg}</span>
            </div>
        }
        .into_any(),

        Load::Ready(data) => {
            let (s, h) = *data;
            let now = now_ms();

            // ---- indexes -------------------------------------------------
            let counts: HashMap<String, (i64, i64, f64)> = s
                .tools
                .iter()
                .map(|t| (t.id.clone(), (t.clicks, t.installs, t.last)))
                .collect();

            // Where each tool lives, for briefs and the demand list. A tool id
            // can appear in several disciplines; first occurrence wins.
            let mut paths: HashMap<String, Vec<String>> = HashMap::new();
            let mut metas: HashMap<String, (String, String, bool)> = HashMap::new();
            let mode_names: HashMap<String, String> =
                h.modes.iter().map(|m| (m.id.clone(), m.name.clone())).collect();
            {
                let mut note = |path: String, t: &HTool| {
                    paths.entry(t.id.clone()).or_default().push(path);
                    metas
                        .entry(t.id.clone())
                        .or_insert_with(|| (t.label.clone(), t.tooltip.clone(), t.wired));
                };
                for m in &h.modes {
                    if m.disciplines.is_empty() {
                        for tab in &m.tabs {
                            for sec in &tab.sections {
                                for t in &sec.tools {
                                    note(
                                        format!("{} ▸ {} ▸ {}", m.name, tab.name, sec.name),
                                        t,
                                    );
                                }
                            }
                        }
                    } else {
                        for d in &m.disciplines {
                            for tab in &d.tabs {
                                for sec in &tab.sections {
                                    for t in &sec.tools {
                                        note(
                                            format!(
                                                "{} ▸ {} ▸ {} ▸ {}",
                                                m.name, d.name, tab.name, sec.name
                                            ),
                                            t,
                                        );
                                    }
                                }
                            }
                        }
                    }
                }
            }

            let mut comments_by_tool: HashMap<String, Vec<CommentRow>> = HashMap::new();
            for c in &s.comments {
                if !c.tool.is_empty() {
                    comments_by_tool.entry(c.tool.clone()).or_default().push(c.clone());
                }
            }

            // Brief for a tool id, pulling everything known about it together.
            let brief_for = {
                let paths = paths.clone();
                let metas = metas.clone();
                let counts = counts.clone();
                let comments_by_tool = comments_by_tool.clone();
                move |id: &str| -> String {
                    let empty_meta = (id.to_string(), String::new(), false);
                    let (label, tooltip, wired) = metas.get(id).cloned().unwrap_or(empty_meta);
                    let (clicks, installs, last) = counts.get(id).copied().unwrap_or((0, 0, 0.0));
                    let no_comments: Vec<CommentRow> = Vec::new();
                    let cmts = comments_by_tool.get(id).unwrap_or(&no_comments);
                    let path = path_line(&paths, id, None);
                    feature_brief(BriefInput {
                        id,
                        label: &label,
                        tooltip: &tooltip,
                        wired,
                        path: &path,
                        clicks,
                        installs,
                        last,
                        comments: cmts,
                    })
                }
            };

            // ---- headline numbers ----------------------------------------
            let total_clicks: i64 = s.tools.iter().map(|t| t.clicks).sum();
            let dream_clicks: i64 = s
                .tools
                .iter()
                .filter(|t| !metas.get(&t.id).map(|m| m.2).unwrap_or(false))
                .map(|t| t.clicks)
                .sum();
            let sessions_14d: i64 = s.sessions_by_day.iter().map(|d| d.count).sum();
            let comment_count = s.comments.len();

            // ---- sessions sparkline (14 days) ----------------------------
            let peak = s.sessions_by_day.iter().map(|d| d.count).max().unwrap_or(0).max(1);
            let bars = s
                .sessions_by_day
                .iter()
                .map(|d| {
                    let pct = (d.count as f64 / peak as f64 * 100.0).max(if d.count > 0 { 6.0 } else { 2.0 });
                    view! {
                        <div class="admin-bar" title=format!("{} — {} session(s)", d.date, d.count)>
                            <div
                                class="admin-bar-fill"
                                class:tel-bar-empty=d.count == 0
                                style=format!("height:{pct:.1}%")
                            ></div>
                        </div>
                    }
                })
                .collect_view();
            let first_day = s.sessions_by_day.first().map(|d| d.date.clone()).unwrap_or_default();
            let last_day = s.sessions_by_day.last().map(|d| d.date.clone()).unwrap_or_default();

            // ---- recent feed (comments + sessions, newest first) ----------
            enum Feed {
                Comment(CommentRow),
                Session(RecentSession),
            }
            let mut feed: Vec<(f64, Feed)> = Vec::new();
            for c in &s.comments {
                feed.push((c.ts, Feed::Comment(c.clone())));
            }
            for r in &s.recent {
                feed.push((r.ts, Feed::Session(r.clone())));
            }
            feed.sort_by(|a, b| b.0.partial_cmp(&a.0).unwrap_or(std::cmp::Ordering::Equal));
            feed.truncate(40);

            let feed_empty = feed.is_empty();

            // "Copy all" — one paste that briefs an entire work session.
            let copy_all = {
                let mut out = String::from(
                    "# Eustress alpha — recent tool demand\n\nPasted from /admin/telemetry. Each block is a self-contained request.\n\n",
                );
                for (_, item) in feed.iter().take(15) {
                    match item {
                        Feed::Comment(c) => {
                            if c.tool.is_empty() {
                                out.push_str(&format!(
                                    "---\n\n# General feedback ({})\n\n\"{}\"\n\n",
                                    stamp(c.ts),
                                    c.text.trim()
                                ));
                            } else {
                                out.push_str("---\n\n");
                                out.push_str(&brief_for(&c.tool));
                                out.push('\n');
                            }
                        }
                        Feed::Session(r) => {
                            out.push_str(&format!(
                                "---\n\n# Session {} — mode {}, {} click(s)\n",
                                stamp(r.ts),
                                if r.mode.is_empty() { "?" } else { &r.mode },
                                r.total
                            ));
                            let prefer = mode_names.get(&r.mode).map(|s| s.as_str());
                            for (id, n) in r.tools.iter().take(8) {
                                let p = path_line(&paths, id, prefer);
                                out.push_str(&format!(
                                    "  - {} ×{}  ({})\n",
                                    id,
                                    n,
                                    if p.is_empty() { "—".to_string() } else { p }
                                ));
                            }
                            out.push('\n');
                        }
                    }
                }
                out
            };

            let feed_rows = feed
                .into_iter()
                .map(|(ts, item)| match item {
                    Feed::Comment(c) => {
                        let tool_label = if c.tool.is_empty() {
                            "General feedback".to_string()
                        } else {
                            metas
                                .get(&c.tool)
                                .map(|m| m.0.clone())
                                .unwrap_or_else(|| c.tool.clone())
                        };
                        let path = path_line(&paths, &c.tool, None);
                        let copy = if c.tool.is_empty() {
                            format!(
                                "# General feedback ({})\n\n\"{}\"\n\n(install {})\n",
                                stamp(ts),
                                c.text.trim(),
                                c.install
                            )
                        } else {
                            brief_for(&c.tool)
                        };
                        view! {
                            <article class="tel-feed-item tel-feed-comment">
                                <div class="tel-feed-head">
                                    <span class="tel-feed-kind tel-feed-kind-said">"SAID"</span>
                                    <span class="tel-feed-title">{tool_label}</span>
                                    <span class="tel-feed-time">{rel_time(ts, now)}</span>
                                    <CopyBtn text=copy strong=true />
                                </div>
                                <blockquote class="tel-feed-quote">{c.text.clone()}</blockquote>
                                <div class="tel-feed-sub">
                                    {(!path.is_empty()).then(|| view! { <span class="tel-path">{path}</span> })}
                                    <code class="tel-tool-id">{c.install.clone()}</code>
                                </div>
                            </article>
                        }
                        .into_any()
                    }
                    Feed::Session(r) => {
                        let chips = r
                            .tools
                            .iter()
                            .take(6)
                            .map(|(id, n)| {
                                let label = metas
                                    .get(id)
                                    .map(|m| m.0.clone())
                                    .unwrap_or_else(|| id.clone());
                                let brief = brief_for(id);
                                view! {
                                    <button
                                        type="button"
                                        class="tel-tool-chip"
                                        title=format!("{id} — click to copy its implementation brief")
                                        on:click=move |ev| {
                                            ev.prevent_default();
                                            copy_text(&brief);
                                        }
                                    >
                                        <span>{label}</span>
                                        <span class="tel-tool-chip-n">{format!("×{n}")}</span>
                                    </button>
                                }
                            })
                            .collect_view();
                        let more = r.tools.len().saturating_sub(6);
                        let session_copy = {
                            let mut out = format!(
                                "# Session {} — mode {}, {} click(s), engine {}\n\n",
                                stamp(ts),
                                if r.mode.is_empty() { "?" } else { &r.mode },
                                r.total,
                                if r.version.is_empty() { "?" } else { &r.version }
                            );
                            let prefer = mode_names.get(&r.mode).map(|x| x.as_str());
                            for (id, n) in r.tools.iter() {
                                let p = path_line(&paths, id, prefer);
                                out.push_str(&format!(
                                    "  - {} ×{}  ({})\n",
                                    id,
                                    n,
                                    if p.is_empty() { "—".to_string() } else { p }
                                ));
                            }
                            out.push_str("\nFull briefs: open /admin/telemetry and copy per tool.\n");
                            out
                        };
                        view! {
                            <article class="tel-feed-item">
                                <div class="tel-feed-head">
                                    <span class="tel-feed-kind tel-feed-kind-used">"USED"</span>
                                    <span class="tel-feed-title">
                                        {if r.mode.is_empty() { "Session".to_string() } else { r.mode.clone() }}
                                        <span class="tel-feed-count">{format!(" · {} clicks", r.total)}</span>
                                    </span>
                                    <span class="tel-feed-time">{rel_time(ts, now)}</span>
                                    <CopyBtn text=session_copy />
                                </div>
                                <div class="tel-chips">
                                    {chips}
                                    {(more > 0).then(|| view! { <span class="tel-more">{format!("+{more} more")}</span> })}
                                </div>
                            </article>
                        }
                        .into_any()
                    }
                })
                .collect_view();

            // ---- wiring queue --------------------------------------------
            let top_rows = s
                .tools
                .iter()
                .take(12)
                .enumerate()
                .map(|(i, t)| {
                    let label = metas.get(&t.id).map(|m| m.0.clone()).unwrap_or_else(|| t.id.clone());
                    let path = path_line(&paths, &t.id, None);
                    let wired = metas.get(&t.id).map(|m| m.2).unwrap_or(false);
                    let width = (t.clicks as f64 / s.tools.first().map(|x| x.clicks.max(1)).unwrap_or(1) as f64
                        * 100.0)
                        .clamp(3.0, 100.0);
                    let brief = brief_for(&t.id);
                    view! {
                        <div class="tel-q-row">
                            <span class="tel-q-rank">{format!("{}", i + 1)}</span>
                            <div class="tel-q-main">
                                <div class="tel-q-line">
                                    <span class="tel-q-label">{label}</span>
                                    <span
                                        class="tel-chip"
                                        class:tel-chip-wired=wired
                                        class:tel-chip-dream=!wired
                                    >
                                        {if wired { "WIRED" } else { "DREAM" }}
                                    </span>
                                    {count_badge(t.clicks, t.installs)}
                                </div>
                                <div class="tel-q-meter">
                                    <div class="tel-q-meter-fill" style=format!("width:{width:.1}%")></div>
                                </div>
                                <div class="tel-q-path">{path}</div>
                            </div>
                            <CopyBtn text=brief />
                        </div>
                    }
                })
                .collect_view();

            // ---- full surface tree ---------------------------------------
            // Filtering is per-node reactive (fine-grained: a keystroke toggles
            // classes, it does not re-render ~1,400 rows).
            let modes = h
                .modes
                .iter()
                .map(|m| {
                    let mut mode_hay = m.name.to_lowercase();
                    let mut mode_total = 0i64;

                    let inner = if m.disciplines.is_empty() {
                        let (v, hay, total) =
                            tabs_view(&m.tabs, &counts, &comments_by_tool, &brief_for, now, query, active_only, expand);
                        mode_hay.push(' ');
                        mode_hay.push_str(&hay);
                        mode_total += total;
                        v.into_any()
                    } else {
                        let mut discs = Vec::new();
                        for d in &m.disciplines {
                            let (tabs, hay, total) = tabs_view(
                                &d.tabs,
                                &counts,
                                &comments_by_tool,
                                &brief_for,
                                now,
                                query,
                                active_only,
                                expand,
                            );
                            let disc_hay = format!("{} {}", d.name.to_lowercase(), hay);
                            mode_hay.push(' ');
                            mode_hay.push_str(&disc_hay);
                            mode_total += total;

                            let hay_v = disc_hay.clone();
                            let visible = move || node_visible(&hay_v, total, query, active_only);
                            let hay_o = disc_hay.clone();
                            let open = move || node_open(&hay_o, total, query, expand);
                            discs.push(view! {
                                <details class="tel-node tel-discipline" class:tel-hidden=move || !visible() prop:open=open>
                                    <summary>
                                        <span class="tel-caret"></span>
                                        <span class="tel-disc-name">{d.name.clone()}</span>
                                        {total_badge(total)}
                                    </summary>
                                    <div class="tel-children">{tabs}</div>
                                </details>
                            });
                        }
                        discs.into_iter().collect_view().into_any()
                    };

                    let accent = if m.color.is_empty() { "#8b949e".to_string() } else { m.color.clone() };
                    let hay_v = mode_hay.clone();
                    let visible = move || node_visible(&hay_v, mode_total, query, active_only);
                    let hay_o = mode_hay.clone();
                    let open = move || node_open(&hay_o, mode_total, query, expand);
                    let disc_note = if m.disciplines.is_empty() {
                        format!("{} tabs", m.tabs.len())
                    } else {
                        format!("{} disciplines", m.disciplines.len())
                    };
                    view! {
                        <details
                            class="tel-node tel-mode"
                            class:tel-hidden=move || !visible()
                            prop:open=open
                            style=format!("--tel-accent:{accent}")
                        >
                            <summary>
                                <span class="tel-caret"></span>
                                <span class="tel-mode-dot"></span>
                                <span class="tel-mode-name">{m.name.clone()}</span>
                                <span class="tel-node-note">{disc_note}</span>
                                {total_badge(mode_total)}
                            </summary>
                            <div class="tel-children">{inner}</div>
                        </details>
                    }
                })
                .collect_view();

            let generated = s.generated_at.clone();

            view! {
                <div class="admin-wrap">
                    <section class="admin-headline tel-headline">
                        <div class="admin-hero-card admin-hero-primary">
                            <span class="admin-hero-value">{thousands(total_clicks)}</span>
                            <span class="admin-hero-label">"Tool clicks (all time)"</span>
                        </div>
                        <div class="admin-hero-card">
                            <span class="admin-hero-value">{thousands(dream_clicks)}</span>
                            <span class="admin-hero-label">"Dream-button votes"</span>
                        </div>
                        <div class="admin-hero-card">
                            <span class="admin-hero-value">{thousands(s.tools.len() as i64)}</span>
                            <span class="admin-hero-label">"Distinct tools touched"</span>
                        </div>
                        <div class="admin-hero-card">
                            <span class="admin-hero-value">{thousands(sessions_14d)}</span>
                            <span class="admin-hero-label">"Sessions (14 days)"</span>
                        </div>
                        <div class="admin-hero-card">
                            <span class="admin-hero-value">{thousands(comment_count as i64)}</span>
                            <span class="admin-hero-label">"Written requests"</span>
                        </div>
                    </section>

                    <section class="tel-split">
                        <div class="dashboard-section tel-panel">
                            <div class="section-header-industrial tel-panel-head">
                                <h2>"Recent requests"</h2>
                                <CopyBtn text=copy_all label="Copy top 15" strong=true />
                            </div>
                            <p class="tel-panel-sub">
                                "Newest first. Every Copy button yields a complete implementation brief — where the button lives, what it promises, what users said, and which files to touch."
                            </p>
                            <div class="tel-feed">
                                {if feed_empty {
                                    view! {
                                        <p class="tel-empty">
                                            "Nothing yet. Clicks arrive when a tester quits the engine; written requests arrive via Help ▸ Send Feedback."
                                        </p>
                                    }
                                        .into_any()
                                } else {
                                    feed_rows.into_any()
                                }}
                            </div>
                        </div>

                        <div class="tel-side">
                            <div class="dashboard-section tel-panel">
                                <div class="section-header-industrial"><h2>"Sessions"</h2></div>
                                <div class="admin-bars tel-bars">{bars}</div>
                                <div class="tel-axis">
                                    <span>{first_day}</span>
                                    <span class="tel-axis-peak">{format!("peak {peak}")}</span>
                                    <span>{last_day}</span>
                                </div>
                            </div>

                            <div class="dashboard-section tel-panel">
                                <div class="section-header-industrial"><h2>"Wiring queue"</h2></div>
                                <p class="tel-panel-sub">"Ranked by distinct installs, then clicks — build down this list."</p>
                                <div class="tel-queue">{top_rows}</div>
                            </div>
                        </div>
                    </section>

                    <section class="dashboard-section tel-panel">
                        <div class="section-header-industrial tel-panel-head">
                            <h2>"Full surface"</h2>
                            <span class="tel-breadcrumb">"mode ▸ discipline ▸ tab ▸ section ▸ button"</span>
                        </div>
                        <div class="tel-controls">
                            <input
                                class="tel-search"
                                type="search"
                                placeholder="Filter by tool, id, tooltip, section…"
                                prop:value=move || query.get()
                                on:input=move |ev| query.set(event_target_value(&ev))
                            />
                            <label class="tel-toggle">
                                <input
                                    type="checkbox"
                                    prop:checked=move || active_only.get()
                                    on:change=move |ev| active_only.set(event_target_checked(&ev))
                                />
                                <span>"Only tools with activity"</span>
                            </label>
                            <div class="tel-btn-row">
                                <button type="button" class="tel-ghost" on:click=move |_| expand.set(1)>"Expand all"</button>
                                <button type="button" class="tel-ghost" on:click=move |_| expand.set(-1)>"Collapse all"</button>
                                <button type="button" class="tel-ghost" on:click=move |_| expand.set(0)>"Auto"</button>
                            </div>
                        </div>
                        <div class="tel-tree">{modes}</div>
                    </section>

                    <p class="admin-generated">"Generated " {generated}</p>
                </div>
            }
            .into_any()
        }
    };

    view! {
        <div class="page page-admin page-admin-telemetry">
            <CentralNav active="admin".to_string() />
            <section class="dashboard-hero">
                <div class="hero-header">
                    <div class="header-line"></div>
                    <span class="header-tag">"ADMIN"</span>
                    <div class="header-line"></div>
                </div>
                <h1 class="dashboard-title">"Tool Telemetry"</h1>
                <p class="dashboard-subtitle">
                    "Anonymous demand for the discipline surface. ⬦ distinct installs · × clicks. "
                    <a href="/admin">"← funnel dashboard"</a>
                </p>
            </section>

            <div class="dashboard-container">{body}</div>
            <Footer />
        </div>
    }
}

// -----------------------------------------------------------------------------
// Tree node predicates — shared by every level so filtering behaves uniformly
// -----------------------------------------------------------------------------

fn node_visible(hay: &str, total: i64, query: RwSignal<String>, active_only: RwSignal<bool>) -> bool {
    let q = query.get();
    let q = q.trim().to_lowercase();
    (q.is_empty() || hay.contains(&q)) && (!active_only.get() || total > 0)
}

fn node_open(hay: &str, total: i64, query: RwSignal<String>, expand: RwSignal<i32>) -> bool {
    match expand.get() {
        1 => true,
        -1 => false,
        _ => {
            let q = query.get();
            let q = q.trim().to_lowercase();
            if !q.is_empty() {
                hay.contains(&q)
            } else {
                total > 0
            }
        }
    }
}

/// Renders a tab list, returning (view, search haystack, total clicks) so the
/// parent can build its own haystack/total without walking the tree twice.
#[allow(clippy::too_many_arguments)]
fn tabs_view(
    tabs: &[HTab],
    counts: &HashMap<String, (i64, i64, f64)>,
    comments_by_tool: &HashMap<String, Vec<CommentRow>>,
    brief_for: &impl Fn(&str) -> String,
    now: f64,
    query: RwSignal<String>,
    active_only: RwSignal<bool>,
    expand: RwSignal<i32>,
) -> (impl IntoView, String, i64) {
    let mut all_hay = String::new();
    let mut all_total = 0i64;
    let mut views = Vec::new();

    for tab in tabs {
        let mut tab_hay = tab.name.to_lowercase();
        let mut tab_total = 0i64;
        let mut sections = Vec::new();

        for sec in &tab.sections {
            let mut sec_hay = sec.name.to_lowercase();
            let mut sec_total = 0i64;
            let mut tools = Vec::new();

            for t in &sec.tools {
                let (clicks, installs, last) = counts.get(&t.id).copied().unwrap_or((0, 0, 0.0));
                sec_total += clicks;
                let hay = hay_of_tool(t);
                sec_hay.push(' ');
                sec_hay.push_str(&hay);

                let cmts = comments_by_tool.get(&t.id).cloned().unwrap_or_default();
                let has_activity = clicks > 0 || !cmts.is_empty();
                let hay_v = hay.clone();
                let visible = move || {
                    let q = query.get();
                    let q = q.trim().to_lowercase();
                    (q.is_empty() || hay_v.contains(&q)) && (!active_only.get() || has_activity)
                };

                let comment_block = (!cmts.is_empty()).then(|| {
                    cmts.iter()
                        .map(|c| {
                            view! {
                                <div class="tel-tool-comment">
                                    <span class="tel-quote-mark">"“"</span>
                                    <span class="tel-quote-text">{c.text.clone()}</span>
                                    <span class="tel-quote-meta">
                                        {format!("{} · {}", c.install.clone(), rel_time(c.ts, now))}
                                    </span>
                                </div>
                            }
                        })
                        .collect_view()
                });
                let comment_badge = (!cmts.is_empty()).then(|| {
                    let n = cmts.len();
                    view! {
                        <span class="tel-cmt-badge" title=format!("{n} written request(s) about this button")>
                            {format!("💬 {n}")}
                        </span>
                    }
                });
                let last_seen = (last > 0.0).then(|| {
                    view! { <span class="tel-last">{rel_time(last, now)}</span> }
                });

                let wired = t.wired;
                tools.push(view! {
                    <div
                        class="tel-tool"
                        class:tel-tool-zero=!has_activity
                        class:tel-tool-said=!cmts.is_empty()
                        class:tel-hidden=move || !visible()
                    >
                        <div class="tel-tool-line">
                            <span
                                class="tel-chip"
                                class:tel-chip-wired=wired
                                class:tel-chip-dream=!wired
                            >
                                {if wired { "WIRED" } else { "DREAM" }}
                            </span>
                            <span class="tel-tool-label" title=t.tooltip.clone()>
                                {t.label.clone()}
                            </span>
                            <code class="tel-tool-id">{t.id.clone()}</code>
                            {comment_badge}
                            {last_seen}
                            {count_badge(clicks, installs)}
                            <CopyBtn text=brief_for(&t.id) />
                        </div>
                        {comment_block}
                    </div>
                });
            }

            tab_total += sec_total;
            tab_hay.push(' ');
            tab_hay.push_str(&sec_hay);

            let hay_v = sec_hay.clone();
            let visible = move || node_visible(&hay_v, sec_total, query, active_only);
            sections.push(view! {
                <div class="tel-section" class:tel-hidden=move || !visible()>
                    <div class="tel-section-name">
                        <span>{sec.name.clone()}</span>
                        {(sec_total > 0).then(|| view! { <span class="tel-section-count">{format!("{sec_total}×")}</span> })}
                    </div>
                    <div class="tel-tools">{tools}</div>
                </div>
            });
        }

        all_total += tab_total;
        all_hay.push(' ');
        all_hay.push_str(&tab_hay);

        let hay_v = tab_hay.clone();
        let visible = move || node_visible(&hay_v, tab_total, query, active_only);
        let hay_o = tab_hay.clone();
        let open = move || node_open(&hay_o, tab_total, query, expand);
        let color = if tab.color.is_empty() { "#8b949e".to_string() } else { tab.color.clone() };
        views.push(view! {
            <details
                class="tel-node tel-tab"
                class:tel-hidden=move || !visible()
                prop:open=open
                style=format!("--tel-tab-color:{color}")
            >
                <summary>
                    <span class="tel-caret"></span>
                    <span class="tel-tab-name">{tab.name.clone()}</span>
                    {total_badge(tab_total)}
                </summary>
                <div class="tel-children">{sections}</div>
            </details>
        });
    }

    (views.into_iter().collect_view(), all_hay, all_total)
}
