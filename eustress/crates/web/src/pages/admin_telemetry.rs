fn copy_text(s: &str) {
    if let Some(win) = web_sys::window() {
        let _ = win.navigator().clipboard().write_text(s);
    }
}

/// Copy button that flashes "Copied" and reverts. `text` is precomputed at
/// render time so the click handler stays synchronous — browsers only honour
/// clipboard writes inside a real user gesture.
#[component]
fn CopyBtn(
    text: String,
    #[prop(optional, into)] label: String,
    #[prop(optional)] strong: bool,
) -> impl IntoView {
    let done = RwSignal::new(false);
    let payload = StoredValue::new(text);
    let idle = if label.is_empty() { "Copy".to_string() } else { label };
    let idle_for_view = idle.clone();
    view! {
        <button
            type="button"
            class="tel-copy"
            class:tel-copy-strong=strong
            class:tel-copy-done=move || done.get()
            title="Copy an implementation brief for this tool — paste straight into Claude Code"
            on:click=move |ev| {
                ev.stop_propagation();
                ev.prevent_default();
                copy_text(&payload.get_value());
                done.set(true);
                spawn_local(async move {
                    gloo_timers::future::TimeoutFuture::new(1500).await;
                    done.set(false);
                });
            }
        >
            {move || if done.get() { "Copied ✓".to_string() } else { idle_for_view.clone() }}
        </button>
    }
}

