// =============================================================================
// Eustress Web - Admin Tool Telemetry (/admin/telemetry)
// =============================================================================
// Demand ranking for the engine's discipline-tool surface: which of the
// ~1,400 (mostly aspirational) ribbon tools people actually click, and what
// they say about them. Live counts come from GET /api/telemetry/summary
// (gated server-side by requireAdmin — non-admins see the denied state); the
// mode → discipline → tab → section → button skeleton comes from the static
// /assets/tool_hierarchy.json generated by scripts/gen_web_hierarchy.py, so
// the Worker only ever stores counters keyed by tool id.
//
// The page is built around one job: turn a click into a shipped feature. Every
// row that represents demand carries a Copy button whose payload is a complete,
// self-contained implementation brief (where the button lives, what it promises,
// what users said, which files to touch) — paste it into Claude Code and start.
// =============================================================================

