async fn fetch_hierarchy() -> Result<Hierarchy, String> {
    let resp = gloo_net::http::Request::get("/assets/tool_hierarchy.json")
        .send()
        .await
        .map_err(|e| e.to_string())?;
    resp.json::<Hierarchy>().await.map_err(|e| e.to_string())
}

